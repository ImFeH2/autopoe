export function normalizeMentionText(value: string): string {
  return [...value.normalize("NFKC")]
    .map(
      (character) =>
        FULL_CASEFOLD_OVERRIDES.get(character) ?? character.toLowerCase(),
    )
    .join("");
}

export function isMentionNameCharacter(value: string | undefined): boolean {
  return value !== undefined && /[\p{L}\p{N}\p{M}_-]/u.test(value);
}

export function isMentionBoundary(value: string | undefined): boolean {
  return value === undefined || !isMentionNameCharacter(value);
}

export function looksLikeEmailAt(body: string, at: number): boolean {
  let left = at;
  while (left > 0 && /[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]/u.test(body[left - 1])) {
    left -= 1;
  }
  if (left === at) return false;
  const right = body.slice(at + 1).match(/^[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+/u);
  return right !== null;
}

export function codePointOffsetToUtf16(
  body: string,
  offset: number,
): number | null {
  if (!Number.isInteger(offset) || offset < 0) return null;
  let codePoints = 0;
  let utf16 = 0;
  for (const character of body) {
    if (codePoints === offset) return utf16;
    codePoints += 1;
    utf16 += character.length;
  }
  return codePoints === offset ? utf16 : null;
}

export function codePointRangeToUtf16(
  body: string,
  start: number,
  end: number,
): { start: number; end: number } | null {
  const utf16Start = codePointOffsetToUtf16(body, start);
  const utf16End = codePointOffsetToUtf16(body, end);
  return utf16Start === null || utf16End === null || utf16End <= utf16Start
    ? null
    : { start: utf16Start, end: utf16End };
}
